/**
 * Same shape as `en`, but every leaf is `string` rather than its literal type.
 *
 * Without this, `as const` above would require the Hindi values to be *identical
 * strings*, not merely present — so typing `hi: Resources` is what forces every key to
 * exist while letting the words differ.
 */
type Translated<T> = { [K in keyof T]: T[K] extends string ? string : Translated<T[K]> };

export type Resources = Translated<typeof en>;
